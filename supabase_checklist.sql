create table if not exists public.chk_entregas (
  id           text primary key,
  grupo        text not null,
  nome         text not null,
  tamanho      text not null default '',
  tipo         text not null default '',
  obs          text not null default '',
  entregue     boolean not null default false,
  entregue_em  timestamptz,
  atualizado_em timestamptz not null default now()
);

create or replace function public.chk_toca_atualizado() returns trigger language plpgsql as $$
begin new.atualizado_em := now(); return new; end $$;
drop trigger if exists chk_entregas_atualizado on public.chk_entregas;
create trigger chk_entregas_atualizado before update on public.chk_entregas
  for each row execute function public.chk_toca_atualizado();

alter table public.chk_entregas enable row level security;
drop policy if exists chk_entregas_acesso on public.chk_entregas;
create policy chk_entregas_acesso on public.chk_entregas
  for all to anon, authenticated using (true) with check (true);

alter table public.chk_entregas replica identity full;
do $$ begin
  alter publication supabase_realtime add table public.chk_entregas;
exception when duplicate_object then null; end $$;

